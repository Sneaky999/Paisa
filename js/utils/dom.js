// Tiny DOM helpers. User-provided text is ALWAYS inserted via text nodes (never innerHTML), which is
// what keeps notes/category names from ever being interpreted as markup.

const SVG_NS = 'http://www.w3.org/2000/svg';

function append(el, kids) {
  for (const k of kids.flat(Infinity)) {
    if (k == null || k === false || k === true) continue;
    el.append(k instanceof Node ? k : document.createTextNode(String(k)));
  }
}

const PROP_ATTRS = new Set(['value', 'checked', 'selected', 'disabled', 'indeterminate']);

export function h(tag, props, ...kids) {
  const el = document.createElement(tag);
  let deferredValue;
  if (props) {
    for (const [k, v] of Object.entries(props)) {
      if (v == null || v === false) continue;
      if (k === 'class') el.className = v;
      else if (k === 'style' && typeof v === 'object') {
        // Custom properties (--x) only work through setProperty, not property assignment.
        for (const [sk, sv] of Object.entries(v)) { if (sk.startsWith('--')) el.style.setProperty(sk, String(sv)); else el.style[sk] = sv; }
      }
      else if (k === 'dataset') Object.assign(el.dataset, v);
      else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
      else if (k === 'value' && tag === 'select') deferredValue = v; // options must exist first
      else if (PROP_ATTRS.has(k)) el[k] = v;
      else el.setAttribute(k, v === true ? '' : String(v));
    }
  }
  append(el, kids);
  if (deferredValue !== undefined) el.value = deferredValue;
  return el;
}

export function svg(tag, props, ...kids) {
  const el = document.createElementNS(SVG_NS, tag);
  if (props) for (const [k, v] of Object.entries(props)) if (v != null && v !== false) el.setAttribute(k, String(v));
  for (const k of kids.flat(Infinity)) if (k instanceof Node) el.append(k);
  return el;
}

